from typing import Dict

from .utils.step_catalog import load_catalog, categories

GUIDE = """# Judo Framework: guide for AI assistants

Judo is a BDD API testing framework (Behave + Gherkin). Tests are `.feature`
files made of ready-made steps in English and Spanish ({count} steps).

## Golden rules
1. **Never invent a step.** Find it first: `judo steps --search "<text>" --json`
   (or the `search_steps` tool of the Judo MCP server).
2. Write the feature, then check it with `judo validate features/` before running.
3. Run with `judo run features/ --format json [--retries 2]` and read `judo_reports/result.json`.
   When something fails, run `judo explain` before editing the test.
   Failed steps include the error and the masked last request/response.
4. Keep secrets out of features: use `${{VARIABLE}}` and a `.env` file.
5. Do not mix undefined steps with custom ones: custom steps go in `features/steps/`.

## Commands
| Command | Purpose |
|---|---|
| `judo steps --search q [--lang en|es] [--json]` | Find steps |
| `judo validate <paths> [--json]` | Detect undefined/ambiguous steps without running |
| `judo run <paths> [--tags t] [--env e] [--format json] [--rerun-failed]` | Execute tests |
| `judo import curl|openapi|postman <src> -o file.feature [--negative]` | Generate a draft feature (negative cases from OpenAPI) |
| `judo explain` | Classify the failures of the last run (cause + next action) |
| `judo coverage <openapi> features/ [--min 80]` | Which API operations the tests cover |
| `judo mcp` | Start the MCP server (stdio) |
| `judo doctor` | Check the environment |

## Minimal feature
```gherkin
Feature: Users API
  Background:
    Given I have a Judo API client
    And the base URL is "https://api.example.com"

  Scenario: Get a user
    When I send a GET request to "/users/1"
    Then the response status should be 200
    And the response "$.id" should be 1
```

## Step categories
{categories}

## Conditionals, loops and other protocols
- Conditionals take a block of steps in a docstring: `And if the response status is 404 then run`,
  then `And otherwise run`. Loops: `I repeat 3 times`, `for each item in the response "$.items" run`
  (variables `${{item}}`, `${{index}}`), `I retry the following steps up to 3 times with 1 seconds delay`.
  For a docstring nested in a block use `'''`.
- Non-JSON: XML/SOAP (`the response XML "//a/b" should be "x"`), forms (`I send a form POST to ...`),
  CSV/text/binary, SSE (`I open the SSE stream`), GraphQL (`I send the GraphQL query to ...`) and
  gRPC by reflection (`I connect to the gRPC server "host:port"`, needs `judo-framework[grpc]`).
- Search before writing: `judo steps --search "soap"`.

## Conventions
- Spanish features start with `# language: es` only for Gherkin keywords; Judo steps
  work in either language with any keyword.
- Variables: `I extract "$.id" from the response as "userId"`, then `${{userId}}`.
  Also `${{user.address.city}}`, `${{items[0].id}}`, `${{name:-default}}`, `${{env.NAME}}`, `${{uuid()}}`, `${{now()}}`.
- Configuration lives in `config/judo.yaml` (timeout, verify_ssl, retries, environments).
- Use tags (`@smoke`, `@regression`) and filter with `judo run --tags smoke`.
"""

RULES: Dict[str, str] = {
    "kiro": ".kiro/steering/judo-framework.md",
    "cursor": ".cursor/rules/judo-framework.mdc",
    "claude": "CLAUDE.md",
    "generic": "AGENTS.md",
}


def render_guide() -> str:
    catalog = load_catalog()
    cats = "\n".join(f"- `{k}`: {v} steps" for k, v in categories(catalog).items())
    return GUIDE.format(count=len(catalog), categories=cats)


def render_llms_txt() -> str:
    return ("# Judo Framework\n\n> BDD API testing framework for Python (Behave + Gherkin), "
            "EN/ES steps, MCP server included.\n\n"
            "- Find steps: `judo steps --search <text> --json`\n"
            "- Validate: `judo validate features/`\n"
            "- Run: `judo run features/ --format json`\n"
            "- MCP: `judo mcp`\n"
            "- Full guide: AGENTS.md\n")


def files_for(target: str) -> Dict[str, str]:
    """Return {relative_path: content} for the requested assistants."""
    guide = render_guide()
    targets = list(RULES) if target == "all" else [target, "generic"]
    out = {}
    for t in targets:
        if t not in RULES:
            continue
        content = guide
        if t == "kiro":
            content = "---\ninclusion: always\n---\n\n" + guide
        if t == "cursor":
            content = "---\ndescription: Judo Framework API testing rules\nalwaysApply: true\n---\n\n" + guide
        out[RULES[t]] = content
    out["llms.txt"] = render_llms_txt()
    return out


